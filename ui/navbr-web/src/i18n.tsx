const fallbackLanguages: SupportedLanguage[] = [
  { cultureName: "pt-BR", displayName: "Português (Brasil)" },
  { cultureName: "en-US", displayName: "English" },
  { cultureName: "es-ES", displayName: "Español" },
  { cultureName: "de-DE", displayName: "Deutsch" },
  { cultureName: "fr-FR", displayName: "Français" }
];

const I18nContext = createContext<I18nContextValue>({
  cultureName: "en-US",
  languages: fallbackLanguages,
  t: key => dictionaries["en-US"][key] ?? key,
  setLanguage: cultureName => sendCommand("setLanguage", { cultureName })
});

function normalizeCulture(cultureName?: string | null) {
  if (cultureName && dictionaries[cultureName]) return cultureName;
  const short = cultureName?.slice(0, 2).toLowerCase();
  const matched = Object.keys(dictionaries).find(key => key.slice(0, 2).toLowerCase() === short);
  return matched ?? "en-US";
}

export function I18nProvider({
  cultureName,
  languages,
  children
}: {
  cultureName?: string | null;
  languages?: SupportedLanguage[] | null;
  children: ReactNode;
}) {
  const normalized = normalizeCulture(cultureName);
  const value = useMemo<I18nContextValue>(() => {
    const dictionary = dictionaries[normalized] ?? dictionaries["en-US"];
    const fallback = dictionaries["en-US"];
    return {
      cultureName: normalized,
      languages: languages?.length ? languages : fallbackLanguages,
      t: (key, values) => {
        let text = dictionary[key] ?? fallback[key] ?? key;
        if (values) {
          for (const [name, value] of Object.entries(values)) {
            text = text.replaceAll(`{${name}}`, String(value));
          }
        }
        return text;
      },
      setLanguage: nextCulture => sendCommand("setLanguage", { cultureName: nextCulture })
    };
  }, [normalized, languages]);

  useEffect(() => {
    document.documentElement.lang = normalized;
  }, [normalized]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
